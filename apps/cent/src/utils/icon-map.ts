const LEGACY_ICON_RE = /icon-\[(mdi--[a-z0-9-]+)\]/g;

/** 把数据里可能残留的旧 MDI 类名换成 Lucide 类名 */
export function normalizeIconClass(className: string): string {
    return className.replace(
        LEGACY_ICON_RE,
        (_full, name: string) =>
            LEGACY_ICON_MAP[name] ?? "icon-[lucide--shapes]",
    );
}
